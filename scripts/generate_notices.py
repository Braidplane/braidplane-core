"""Refresh the bounded Community dependency notice inventory (not release clearance).

Run from the repository root: python3 -m scripts.generate_notices [--check]
"""

import argparse
import json
import os
from pathlib import Path
import sys

from cli.scripts.release import LICENSE_NAMES, go_json, go_stdout, license_files, third_party_notices
from scripts.package_sources import verify_mpl_inventory


ROOT = Path(__file__).resolve().parent.parent
GO = ("bash", "scripts/go-toolchain.sh")
PACKAGES = (".", "./cmd/frontend", "./cmd/migrate", "./cli/cmd/braidplane")
TARGETS = (("linux", "amd64"), ("linux", "arm64"), ("darwin", "amd64"), ("darwin", "arm64"))
GENERATORS = (
    "github.com/a-h/templ", "github.com/dmarkham/enumer", "github.com/hexdigest/gowrap",
    "github.com/oapi-codegen/oapi-codegen/v2", "github.com/sqlc-dev/sqlc",
)


def generator_notices(root, env):
    sections = [b"\nSource-generator license inventory (not a runtime dependency assertion)\n"]
    for module in GENERATORS:
        metadata = json.loads(go_stdout(root, env, GO, "mod", "download", "-modfile=tools/go.mod", "-json", module))
        if metadata.get("Path") != module or not metadata.get("Version") or not metadata.get("Dir") or metadata.get("Replace"):
            raise ValueError(f"source generator identity is incomplete or replaced: {module}")
        directory = Path(metadata["Dir"])
        documents = license_files(directory)
        if not any(path.name.upper().startswith(LICENSE_NAMES) for path in documents):
            raise ValueError(f"source generator legal documents are missing: {module}")
        sections.append(f"\n{module} {metadata['Version']} (generator input)\n".encode())
        for path in documents:
            sections.append(f"\n--- {path.name} ---\n".encode())
            sections.append(path.read_bytes().rstrip() + b"\n")
    return b"".join(sections)


def generate():
    env = dict(os.environ, CGO_ENABLED="0", GOWORK="off")
    graph = []
    for goos, goarch in (*TARGETS, ("windows", "amd64"), ("windows", "arm64")):
        packages = ("./cli/cmd/braidplane",) if goos == "windows" else PACKAGES
        for cgo in (("0",) if goos == "windows" else ("0", "1")):
            target_env = dict(env, GOOS=goos, GOARCH=goarch, CGO_ENABLED=cgo)
            graph.extend(go_json(ROOT, target_env, packages, GO))
    notices = third_party_notices(ROOT, env, package_graph=graph, go_command=GO)
    verify_mpl_inventory(ROOT, notices)
    notices = notices.replace(b"Braidplane CLI third-party notices", b"Braidplane Community third-party notices", 1)
    sections = [
        b"Generated by python3 -m scripts.generate_notices. Do not edit.\n"
        b"Scope: application/CLI Linux and macOS amd64/arm64 with CGO 0/1; Windows CLI amd64/arm64 with CGO 0.\n"
        b"Named legal files at module roots and selected package ancestors, plus listed assets/CSS inputs.\n"
        b"Selected dependency source headers and pinned source-generator legal documents are retained.\n"
        b"This inventory does not establish rights clearance. See doc/RELEASE_RIGHTS.md.\n\n",
        notices,
    ]
    assets = [ROOT / "pkg/odcs/schema/LICENSE", ROOT / "brand/icons/app/LICENSE"]
    assets.extend(sorted((ROOT / "frontend/assets/vendor").glob("LICENSE*")))
    assets.extend(sorted((ROOT / "brand/icons/data-sources/licenses").iterdir()))
    lock = json.loads((ROOT / "frontend/package-lock.json").read_text())
    for package in ("tailwindcss", "daisyui"):
        directory = ROOT / "frontend/node_modules" / package
        installed = json.loads((directory / "package.json").read_text())["version"]
        if installed != lock["packages"][f"node_modules/{package}"]["version"]:
            raise ValueError(f"{package} installation does not match lockfile; run task frontend-install")
        assets.append(directory / "LICENSE")
    for path in assets:
        sections.append(f"\n--- {path.relative_to(ROOT).as_posix()} ---\n\n".encode())
        sections.append(path.read_bytes() + b"\n")
    sections.append(generator_notices(ROOT, env))
    return b"".join(sections)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = ROOT / "THIRD_PARTY_NOTICES.txt"
    content = generate()
    if args.check:
        if not output.is_file() or output.read_bytes() != content:
            print("THIRD_PARTY_NOTICES.txt is stale; run python3 -m scripts.generate_notices", file=sys.stderr)
            return 1
    else:
        output.write_bytes(content)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
